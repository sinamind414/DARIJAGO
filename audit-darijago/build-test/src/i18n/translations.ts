export function parseAppLanguage(raw: string | null): AppLanguage | null {
  if (!raw) return null;
  const normalized = raw.trim().toLowerCase();
  if (
    normalized === 'fr' ||
    normalized === 'en' ||
    normalized === 'es' ||
    normalized === 'de' ||
    normalized === 'it' ||
    normalized === 'nl' ||
    normalized === 'zh'
  ) {
    return normalized;
  }
  return null;
}

